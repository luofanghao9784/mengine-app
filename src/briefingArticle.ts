function sameEvidence(a: CardData, b: CardData) {
  const pick = (d: CardData) => [
    d.fact,
    d.advice,
    d.source,
    d.value,
    d.unit,
    d.items,
    d.presentation,
    d.refs,
    d.sourceLinks,
  ];
  return JSON.stringify(pick(a)) === JSON.stringify(pick(b));
}

export function buildBriefingArticle(data: CardData): BriefingArticleData {
  const original = kongguCards.find((card) => card.id === data.id);
  const extension =
    original && sameEvidence(data, original) ? extensions[data.id.replace('konggu:', '')] : undefined;
  if (extension) {
    return {
      version: 1,
      sections: [
        { heading: extension[0], paragraphs: [extension[1]] },
        { heading: extension[2], paragraphs: [extension[3]] },
      ],
    };
  }
  return {
    version: 1,
    sections: [
      {
        heading: data.sourceKind === 'conversation' ? '沿着这段会话继续' : '把这条内容放回工作情境',
        paragraphs: [
          data.sourceKind === 'conversation'
            ? '这张卡片保留了当时的会话回复。进入原会话后，可以继续追问其中的依据、补充新的背景，或把尚未解决的问题逐项说明。后续新回复会形成新的画报内容，当前阅读记录仍对应这一版。'
            : `围绕「${data.title}」，可以先确认它对应的时间、适用范围和当前最需要解决的问题，再对照上面的依据判断建议是否适用。卡片中没有提供的信息仍需补充，不应仅凭概要扩展为已经完成的工作或已确认的结论。`,
        ],
      },
      {
        heading: '在会话里进一步展开',
        paragraphs: [
          data.prompts.length
            ? `可以从“${data.prompts[0]}”开始，说明你关心的范围和期望得到的结果。卡片正文与来源会一并带入；如需调整内容，也可以补充缺失的资料、指出不准确之处，或说明希望怎样呈现。`
            : '带着这份正文与来源进入会话，补充实际背景、希望解决的问题和期望的结果，再逐步整理下一步行动。',
        ],
      },
    ],
  };
}

export function withBriefingArticle(reference: BriefingReference): BriefingReference {
  return { ...reference, article: reference.article || buildBriefingArticle(reference.snapshot) };
}
