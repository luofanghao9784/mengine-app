/** 知识的来源类型：0 业务数据、1 资料、2 会话。 */
export const sourceKind: Record<string, number> = {};
const FACT: [string, string, string] = ['项', '内容', '状态'];
const KIND = ['来自业务数据', '来自资料', '来自会话'];

const k = (
  id: string,
  space: string,
  name: string,
  type: string,
  kind: number,
  source: string,
  basis: string,
  attention?: { group: string; tone: Tone; why: string; verdict: string; actions: string[] },
): Item => {
  sourceKind[id] = kind;
  return {
    id,
    group: attention?.group || space,
    name,
    why: attention?.why || `${type} · ${source}`,
    side: kind === 2 ? '仅本人可用' : space,
    tone: attention?.tone || 'ok',
    verdict: attention?.verdict || basis,
    kvHead: FACT,
    kv: [
      ['来源', source, KIND[kind], 'plain'],
      ['类型', type, '', 'plain'],
      ['依据', basis, attention ? '待处理' : '核验通过', attention ? attention.tone : 'ok'],
    ],
    actions: attention?.actions || ['查看来源'],
  };
};
