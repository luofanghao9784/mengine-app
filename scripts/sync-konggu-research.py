"""Compile the approved research into a self-contained, typed frontend fixture.

Only metadata, short source summaries and original image URLs are included.
No original media files are downloaded or redistributed.
"""
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
research = root / 'docs/调研/空谷无界'
index = json.loads((research / '资料索引.json').read_text())
materials = []
for row in index:
    text = (research / row['path']).read_text()
    text = re.sub(r'^---\n.*?\n---\n', '', text, count=1, flags=re.S)
    text = text.split('\n来源底表：')[0].strip()
    text = re.sub(r'^# .+\n', '', text, count=1).strip()
    materials.append({**row, 'content': text})
bundle = {
    'materials': materials,
    'research': json.loads((research / '来源与图片.json').read_text()),
    'business': json.loads((research / '模拟经营底表.json').read_text()),
}
(root / 'src/kongguResearch.ts').write_text(
    '// Generated by scripts/sync-konggu-research.py from the approved research.\n'
    '// Internal business values are synthetic; public source dates remain original.\n'
    + 'export const kongguResearch = ' + json.dumps(bundle, ensure_ascii=False, indent=2) + ';\n'
)
print(f'Compiled {len(materials)} materials, 10 sources and the synthetic baseline.')
